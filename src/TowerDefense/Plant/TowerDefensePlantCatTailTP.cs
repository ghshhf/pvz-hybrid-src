	public override void _Ready()
	{
		base._Ready();
		if (!Engine.IsEditorHint())
		{
			_fireComponent = componentManager.GetRuntime<FireComponent>("character.fire");
			skinName = ResolveSkinName(base.currentCustom);
		}
	}

	public override void OnCustomSwitched(string customKey)
	{
		base.OnCustomSwitched(customKey);
		skinName = ResolveSkinName(customKey);
	}

	private static string ResolveSkinName(string customKey)
	{
		if (!string.IsNullOrEmpty(customKey) && customKey.StartsWith("Custom", StringComparison.Ordinal) && int.TryParse(customKey.Substring("Custom".Length), out var result) && result >= 0 && result < CustomSkinNames.Length)
		{
			return CustomSkinNames[result];
		}
		return "Default";
	}

	private static string ResolveSkinName(Array<string> customKeys)
	{
		foreach (string customKey in customKeys)
		{
			string text = ResolveSkinName(customKey);
			if (text != "Default")
			{
				return text;
			}
		}
		return "Default";
	}

	private void ApplySkinName()
	{
		if (IsNodeReady() && _fireComponent != null && !_fireComponent.IsReleased && _fireComponent.fireCheckList.Count != 0 && _fireComponent.fireCheckList[0].projectile is FireComponentProjectileSingle { projectileData: not null } fireComponentProjectileSingle)
		{
			fireComponentProjectileSingle.projectileData.skinName = new StringName(_skinName);
		}
	}

	public override Dictionary ExportVariantSave()
	{
		Dictionary dictionary = base.ExportVariantSave();
		dictionary["fireNum"] = fireNum;
		dictionary["fireInterval"] = fireInterval;
		dictionary["skinName"] = skinName;
		return dictionary;
	}

	public override void ImportVariantSave(Dictionary data)
	{
		base.ImportVariantSave(data);
