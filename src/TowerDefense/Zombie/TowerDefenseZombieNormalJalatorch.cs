	}

	public override void ImportVariantSave(Dictionary data)
	{
		base.ImportVariantSave(data);
		timer = Math.Max(0.0, data.GetValueOrDefault("timer", timer).AsDouble());
		if (data.ContainsKey("time"))
		{
			time = Math.Max(0.0, data["time"].AsDouble());
		}
		else if (time <= 0.0)
		{
			time = GD.RandRange(7.0, 10.0);
		}
		explode = data.GetValueOrDefault("explode", explode).AsBool();
	}

	public override void _Ready()
	{
		base._Ready();
		if (!Engine.IsEditorHint())
		{
			_zombieSprite = base.sprite as ZombieNormalJalatorchSprite;
			if (!base.IsProgressRestoreInFlight)
			{
				time = GD.RandRange(7.0, 10.0);
			}
			_zombieSprite.head.OnAnimeCompleted += AnimeCompleted;
			ConfigureWaterLineVisualLayers("Zombie_duckytube", "Zombie_whitewater", "Zombie_whitewater2");
		}
	}

	public override void BatchUpdate(double delta)
	{
		base.BatchUpdate(delta);
		if (!Engine.IsEditorHint() && GodotObject.IsInstanceValid(TowerDefenseManager.Instance.currentControl) && TowerDefenseManager.Instance.currentControl.isGameRunning && base.IsInsideComponentBattlefield && !explode && CanRunAbility())
		{
			if (timer < time)
			{
				timer += delta * timeScale;
				return;
			}
			explode = true;
			AudioManager.Instance.AudioPlay("ReverseExplosion");
			_zombieSprite.head.SetAnimation("Explode", loop: false);
			_zombieSprite.head.timeScale = 1.0;
		}
	}

	public override void WalkProcessing(double delta)
	{
		if ((double)GetGlobalPositionForPhysicsFrame(TowerDefenseProcessModeDispatch.CurrentPhysicsFrame).X > TowerDefenseManager.Instance.GetMapGroundRight())
		{
			base.sprite.timeScale = timeScale * base.walkSpeedScale * 2.0;
		}
		else
		{
			base.sprite.timeScale = timeScale * base.walkSpeedScale;
		}
		if (!base.sprite.pause && attackComponent.CanAttack())
		{
			Attack();
		}
	}

	public override void AttackEntered()
	{
		base.AttackEntered();
		if (HasShield())
		{
			base.sprite.SetFliters(new Godot.Collections.Array { "Zombie_outerarm_upper" }, open: true);
			base.sprite.SetFliters(new Godot.Collections.Array { "Zombie_outerarm_hand", "Zombie_outerarm_lower" }, open: true);
		}
	}

	public override void AttackExited()
	{
		base.AttackExited();
		if (HasShield())
		{
