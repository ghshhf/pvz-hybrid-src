		}
	}

	public override void DieProcessing(double delta)
	{
		base.DieProcessing(delta);
		base.sprite.timeScale = timeScale * 2.0;
	}

	public override void DamagePointReach(string damagePointName)
	{
		base.DamagePointReach(damagePointName);
		if (!(damagePointName == "Arm"))
		{
			if (damagePointName == "Head")
			{
				DamagePartCreate("Head", _zombieSprite.head, new Vector2(GD.RandRange(-100, 100), -300f), keepSlotScale: false, new Vector2(-25f, -30f), fromSync: false, null, 0L);
			}
		}
		else
		{
			base.sprite.SetFliters(new Godot.Collections.Array { "Zombie_outerarm_upper" }, open: true);
		}
	}

	public override void ArmorDamagePointReach(string armorName, int stage)
	{
		base.ArmorDamagePointReach(armorName, stage);
		if (HasShield() && stage > 0)
		{
			base.sprite.SetFliters(new Godot.Collections.Array { "Zombie_outerarm_upper" }, open: true);
		}
	}

	public override void AnimeCompleted(string clip)
	{
		base.AnimeCompleted(clip);
		if (clip == "Explode")
		{
			base.Visible = false;
			CreateJalatorchFireColumn();
			Destroy();
		}
	}

	private void CreateJalatorchFireColumn()
	{
		if (!TowerDefenseManager.HasGameplayAuthority)
		{
			return;
		}
		TowerDefenseCharacter.CreateJalapenoFireColumn(base.camp, base.gridPos, 1800.0, null, null, "Fire", suppressDeathrattles: true);
		TowerDefensePacketConfig packetConfig = TowerDefenseManager.GetPacketConfig("ItemMegaFire");
		if (!GodotObject.IsInstanceValid(packetConfig))
		{
			return;
		}
		Vector2I mapGridNum = TowerDefenseManager.Instance.GetMapGridNum();
		for (int i = 0; i < mapGridNum.Y; i++)
		{
			bool flag = true;
			if (i == 0)
			{
				PlantMegaFire(base.gridPos);
				flag = false;
			}
			else
			{
				if (base.gridPos.Y - i > 0)
				{
					PlantMegaFire(base.gridPos - new Vector2I(0, i));
					flag = false;
				}
				if (base.gridPos.Y + i <= mapGridNum.Y)
				{
					PlantMegaFire(base.gridPos + new Vector2I(0, i));
					flag = false;
				}
			}
			if (flag)
			{
				break;
			}
		}
		void PlantMegaFire(Vector2I targetGridPos)
		{
			TowerDefenseCharacter towerDefenseCharacter = packetConfig.Plant(targetGridPos);
			if (GodotObject.IsInstanceValid(towerDefenseCharacter))
			{
				if (!instance.hypnoses)
				{
					towerDefenseCharacter.Hypnoses();
				}
				TowerDefenseManager.PublishSpawnedCharacter("ItemMegaFire", towerDefenseCharacter, useCreate: false);
			}
		}
	}

	public override void Purify()
	{
		if (!GodotObject.IsInstanceValid(cell))
		{
			return;
		}
		if (Global.IsMultiplayerMode && !MultiPlayerManager.Instance.isHost)
		{
			Destroy();
			return;
		}
		TowerDefensePacketConfig packetConfig = TowerDefenseManager.GetPacketConfig("PlantJalaTorch");
		if (cell.CanPacketPlant(packetConfig))
		{
			TowerDefenseCharacter towerDefenseCharacter = packetConfig.Plant(base.gridPos);
			towerDefenseCharacter.WakeUp();
			if (instance.hypnoses)
			{
				towerDefenseCharacter.Hypnoses();
			}
			if (Global.IsMultiplayerMode && MultiPlayerManager.Instance.isHost)
			{
				TowerDefenseControlNew currentControl = TowerDefenseManager.Instance.currentControl;
				if (GodotObject.IsInstanceValid(currentControl))
				{
					int nextSyncId = currentControl.GetNextSyncId();
					currentControl.RegisterSyncCharacter(nextSyncId, towerDefenseCharacter);
					MultiPlayerManager.Instance.SendSpawnCharacterAt("PlantJalaTorch", base.gridPos.X, base.gridPos.Y, nextSyncId);
				}
			}
		}
		Destroy();
	}

